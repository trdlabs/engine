// S2 — RNG актора с ИЗВЛЕКАЕМЫМ состоянием (§3.6).
//
// Зачем понадобился отдельный модуль при уже существующем `determinism/rng.ts`. Тот прячет своё
// состояние в замыкании: `createSeededRng(seed)` возвращает объект с `next()`, и достать текущее
// положение генератора снаружи нельзя ничем. Для v1 этого хватало — прогон шёл от начала до конца.
//
// Для актора не хватает. §3.6 требует, чтобы состояние RNG лежало в `engineState.rng` и
// чекпойнтилось вместе с остальным ядром. Стратегия, дёрнувшая `ctx.rng.next()` до чекпойнта,
// после восстановления обязана продолжить ТУ ЖЕ последовательность — иначе Л2 поймает расхождение
// на первом же чекпойнте, причём расхождение будет выглядеть как «стратегия передумала».
//
// ДОМ RNG — ЯДРО, А НЕ АВТОРСКОЕ ПОЛЕ. Автор получает `ctx.rng` как capability; положить генератор
// в авторский plain-data слот значило бы, что автор волен его не сохранить, — то есть ровно тот
// класс, что дал tp2: восстановление становится вопросом авторской дисциплины.
//
// Алгоритм тот же mulberry32 и та же последовательность, что у `determinism/rng.ts`, — это
// проверено тестом, а не заявлено: разойдись они, актор и v1-ядро дали бы разные числа при одном
// seed, и происхождение расхождения искали бы в стратегии.

import type { SeededRng } from '../determinism/rng.js';

/**
 * Состояние генератора — plain data, пригодная для канонического кодирования.
 *
 * Одно 32-битное беззнаковое число: у mulberry32 больше состояния нет. Объект, а не голое число,
 * намеренно — поле в чекпойнте обязано быть самоописательным, а `rng: 3921749283` в дампе не
 * говорит читателю ничего.
 */
export interface RngState {
  readonly a: number;
}

/** RNG, чьё состояние можно снять и восстановить. */
export interface CheckpointableRng extends SeededRng {
  /** Снимок текущего положения. Чистая операция: генератор не двигается. */
  snapshot(): RngState;
}

/** Начальное состояние от seed прогона — ровно то же, что у `createSeededRng`. */
export function rngStateFromSeed(seed: number): RngState {
  return { a: seed >>> 0 };
}

/**
 * Создать генератор из состояния.
 *
 * Восстановление и первичное создание — ОДНА операция, а не две: отдельный путь «создать заново»
 * рано или поздно разошёлся бы с путём «восстановить», и расхождение проявилось бы только после
 * первого краха, то есть в самый неудобный момент.
 */
export function createCheckpointableRng(state: RngState): CheckpointableRng {
  let a = state.a >>> 0;
  return {
    next(): number {
      a = (a + 0x6d2b79f5) | 0;
      let t = Math.imul(a ^ (a >>> 15), 1 | a);
      t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
      return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    },
    snapshot(): RngState {
      return { a: a >>> 0 };
    },
  };
}

/**
 * Проверка состояния, пришедшего из чекпойнта.
 *
 * Чекпойнт — недоверенный вход: он мог быть записан другой версией, повреждён или подделан. Тип
 * `RngState` в рантайме не гарантирует ничего (§3.6), поэтому форма проверяется значением, а
 * несовместимость fail-closed.
 */
export function isRngState(value: unknown): value is RngState {
  if (typeof value !== 'object' || value === null) return false;
  const a = (value as { a?: unknown }).a;
  return typeof a === 'number' && Number.isInteger(a) && a >= 0 && a <= 0xffffffff;
}
