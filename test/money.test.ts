// Правила денежного счёта — как проверяемые свойства, а не как знание в чьей-то голове.
//
// Это половина смысла модуля `money.ts`. Раньше правила жили в комментариях и в памяти: забыл про
// порядок операций — golden'ы поехали, а причину искать в пяти файлах. Здесь каждое правило
// закреплено тестом, который упадёт в тот же день, когда правило нарушат.

import { describe, expect, it } from 'vitest';

import {
  SCALE,
  add,
  addSub,
  div,
  levelFrom,
  min,
  mul,
  portionBps,
  shiftBps,
  sub,
  subAll,
  weightedPrice,
} from '../src/core/money.js';

describe('money — правило «одна функция = одно целое выражение»', () => {
  it('составная операция ТОЧНЕЕ, чем сборка из примитивов', () => {
    // Это и есть причина, по которой в модуле нет универсальных add/sub, из которых можно собрать
    // что угодно. Цепочка внутри Decimal выходит во float64 один раз; сборка из примитивов — два
    // раза, и промежуточный результат округляется до ближайшего double раньше времени.
    //
    // Величины здесь подобраны так, чтобы разница была видна на одном шаге. В движке она
    // накапливается тише, но механизм тот же.
    const a = 1;
    const plus = 1e-18;
    const minus = 1;

    expect(addSub(a, plus, minus)).toBe(1e-18); // одна цепочка — разность сохранилась
    expect(sub(add(a, plus), minus)).toBe(0); // два выхода — разность потеряна

    // Если это равенство когда-нибудь станет верным, значит представление сменилось так, что
    // промежуточное округление исчезло, — и тогда составные функции можно упрощать осознанно.
    expect(addSub(a, plus, minus)).not.toBe(sub(add(a, plus), minus));
  });

  it('subAll держит всю цепочку вычитаний в одной точности', () => {
    expect(subAll(1, 1e-18, -1e-18)).toBe(1);
    expect(subAll(10, 1, 2, 3)).toBe(4);
  });
});

describe('money — правило «внутри не округляем»', () => {
  it('операции НЕ квантуют результат до канонической шкалы', () => {
    // Волна C вынесла квантизацию на границу артефакта. Функция этого модуля, которая округляет,
    // это ошибка, а не оптимизация: она вернула бы пербарную подрезку через чёрный ход.
    const belowScale = 1e-12; // на четыре порядка мельче шага 1e-8
    expect(add(belowScale, 0)).toBe(belowScale);
    expect(mul(belowScale, 1)).toBe(belowScale);
    expect(sub(belowScale, 0)).toBe(belowScale);
    expect(SCALE).toBe(8); // шкала объявлена, но здесь не применяется
  });

  it('деление сохраняет непериодический хвост, а не режет его по шкале', () => {
    // 1000 / 100.05 — бесконечная дробь; наружу обязана выйти полная точность double.
    expect(div(1_000, 100.05)).toBe(1_000 / 100.05);
    expect(div(1_000, 100.05)).not.toBe(9.9950025); // это значение появляется ТОЛЬКО на границе
  });
});

describe('money — арифметические свойства', () => {
  it('сложение коммутативно', () => {
    for (const [a, b] of [
      [0.1, 0.2],
      [1e-8, 12345.6789],
      [-5, 5],
    ]) {
      expect(add(a!, b!)).toBe(add(b!, a!));
    }
  });

  it('min выбирает меньшее, а не первое', () => {
    expect(min(5, 3)).toBe(3);
    expect(min(3, 5)).toBe(3);
    expect(min(-1, 1)).toBe(-1);
  });

  it('десятичная семантика: 0.1 + 0.2 даёт ровно 0.3', () => {
    // Ради этого и держится Decimal: обычное сложение здесь даёт 0.30000000000000004.
    expect(add(0.1, 0.2)).toBe(0.3);
    expect(0.1 + 0.2).not.toBe(0.3);
  });
});

describe('money — доменные операции', () => {
  it('shiftBps двигает цену в обе стороны на заданные bps', () => {
    expect(shiftBps(100, 5, 1)).toBe(100.05); // покупка: +5 bps
    expect(shiftBps(100, 5, -1)).toBe(99.95); // продажа: −5 bps
    expect(shiftBps(100, 0, 1)).toBe(100); // нулевой слиппедж не двигает
  });

  it('portionBps берёт долю в базисных пунктах', () => {
    expect(portionBps(1_000, 10)).toBe(1); // 10 bps от 1000
    expect(portionBps(1_000, 0)).toBe(0);
  });

  it('levelFrom строит уровень защиты от цены входа', () => {
    expect(levelFrom(100, 0.02, -1)).toBe(98); // стоп для long
    expect(levelFrom(100, 0.02, 1)).toBe(102); // тейк для long
  });

  it('weightedPrice усредняет вход по размеру', () => {
    // Долив равным объёмом по вдвое большей цене даёт середину.
    expect(weightedPrice(100, 1, 200, 1, 2)).toBe(150);
    // Долив в девять раз большим объёмом тянет цену к себе.
    expect(weightedPrice(100, 1, 200, 9, 10)).toBe(190);
  });

  it('weightedPrice делит на переданный итог, а не пересчитывает его сам', () => {
    // Знаменатель приходит снаружи, потому что новый размер уже посчитан вызывающим; пересчёт
    // здесь добавил бы лишний выход во float64 ровно там, где мы его избегаем.
    expect(weightedPrice(10, 2, 20, 2, 4)).toBe(15);
  });
});
